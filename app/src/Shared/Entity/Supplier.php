declare(strict_types=1);

namespace CoolStuff\Shared\Entity;

use Doctrine\ORM\Mapping as ORM;
use CoolStuff\Component\Entity\Entity;
use PHPMentors\DomainKata\Entity\EntityInterface;

#[ORM\Entity]
#[ORM\Table(name: 'suppliers')]
final class Supplier extends Entity implements EntityInterface
{
    #[ORM\Column(type: 'string')]
    private string $firstName;

    #[ORM\Column(type: 'string')]
    private string $lastName;

    #[ORM\Column(type: 'string')]
    private string $mobile;

    #[ORM\Column(type: 'string')]
    private string $email;

    #[ORM\ManyToOne(targetEntity: 'SupplierProductPrice', inversedBy: 'productPrice')]
    private SupplierProductPrice $productPrice;

    public function getFirstName(): string
    {
        return $this->firstName;
    }

    public function setFirstName(string $firstName): self
    {
        $this->firstName = $firstName;

        return $this;
    }

    public function getLastName(): string
    {
        return $this->lastName;
    }

    public function setLastName(string $lastName): self
    {
        $this->lastName = $lastName;

        return $this;
    }

    public function getMobile(): string
    {
        return $this->mobile;
    }

    public function setMobile(string $mobile): self
    {
        $this->mobile = $mobile;

        return $this;
    }

    public function getEmail(): string
    {
        return $this->email;
    }

    public function setEmail(string $email): self
    {
        $this->email = $email;

        return $this;
    }
}
